export function getModule(moduleId) {
  return MODULES.find((m) => m.id === moduleId) ?? null;
}

export function getLesson(lessonId) {
  for (const m of MODULES) {
    const lesson = m.lessons.find((l) => l.id === lessonId);
    if (lesson) return { ...lesson, moduleId: m.id };
  }
  return null;
}

export function getLessonByIndex(moduleId, index) {
  const mod = getModule(moduleId);
  if (!mod) return null;
  const lesson = mod.lessons[index - 1];
  if (!lesson) return null;
  return { ...lesson, moduleId };
}

export function getAllLessonsFlat() {
  return MODULES.flatMap((m) => m.lessons.map((l) => ({ ...l, moduleId: m.id })));
}
